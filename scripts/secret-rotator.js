/**
 * 🔐 SECRET ROTATOR — Rotación de secretos API con vault local
 * 
 * Uso:
 *   node scripts/secret-rotator.js list              # Listar secretos
 *   node scripts/secret-rotator.js rotate alibaba    # Rotar uno
 *   node scripts/secret-rotator.js rotate --all      # Rotar todos
 *   node scripts/secret-rotator.js verify            # Verificar vault
 *   node scripts/secret-rotator.js export --env      # Exportar como .env
 * 
 * SEGURIDAD: El vault se cifra con AES-256-GCM.
 * La master key se deriva de una passphrase + salt.
 * 
 * Variables de entorno:
 *   VAULT_PASSPHRASE   - Passphrase maestra (obligatoria)
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const VAULT_DIR = path.join(__dirname, '..', 'vault');
const VAULT_FILE = path.join(VAULT_DIR, 'secrets.enc');
const VAULT_META = path.join(VAULT_DIR, 'metadata.json');
const ALGORITHM = 'aes-256-gcm';
const KEY_LENGTH = 32;
const IV_LENGTH = 16;
const SALT_LENGTH = 32;
const TAG_LENGTH = 16;
const ITERATIONS = 100000;

// ─── CIFRADO ────────────────────────────────────────────────────────────────
function deriveKey(passphrase, salt) {
  return crypto.pbkdf2Sync(passphrase, salt, ITERATIONS, KEY_LENGTH, 'sha512');
}

function encrypt(plaintext, passphrase) {
  const salt = crypto.randomBytes(SALT_LENGTH);
  const key = deriveKey(passphrase, salt);
  const iv = crypto.randomBytes(IV_LENGTH);
  const cipher = crypto.createCipheriv(ALGORITHM, key, iv);
  
  let encrypted = cipher.update(plaintext, 'utf8', 'hex');
  encrypted += cipher.final('hex');
  const tag = cipher.getAuthTag();
  
  return {
    salt: salt.toString('hex'),
    iv: iv.toString('hex'),
    data: encrypted,
    tag: tag.toString('hex')
  };
}

function decrypt(encryptedObj, passphrase) {
  const salt = Buffer.from(encryptedObj.salt, 'hex');
  const key = deriveKey(passphrase, salt);
  const iv = Buffer.from(encryptedObj.iv, 'hex');
  const tag = Buffer.from(encryptedObj.tag, 'hex');
  
  const decipher = crypto.createDecipheriv(ALGORITHM, key, iv);
  decipher.setAuthTag(tag);
  
  let decrypted = decipher.update(encryptedObj.data, 'hex', 'utf8');
  decrypted += decipher.final('utf8');
  
  return decrypted;
}

// ─── VAULT ──────────────────────────────────────────────────────────────────
class SecretVault {
  constructor(passphrase) {
    this.passphrase = passphrase;
    this.secrets = {};
    this.metadata = {};
    fs.mkdirSync(VAULT_DIR, { recursive: true });
    this._load();
  }
  
  _load() {
    if (fs.existsSync(VAULT_FILE)) {
      try {
        const encrypted = JSON.parse(fs.readFileSync(VAULT_FILE, 'utf-8'));
        const decrypted = decrypt(encrypted, this.passphrase);
        this.secrets = JSON.parse(decrypted);
      } catch (err) {
        console.error('❌ Error descifrando vault. ¿Passphrase correcta?');
        process.exit(1);
      }
    }
    
    if (fs.existsSync(VAULT_META)) {
      this.metadata = JSON.parse(fs.readFileSync(VAULT_META, 'utf-8'));
    }
  }
  
  _save() {
    const plaintext = JSON.stringify(this.secrets);
    const encrypted = encrypt(plaintext, this.passphrase);
    fs.writeFileSync(VAULT_FILE, JSON.stringify(encrypted, null, 2));
    
    this.metadata.lastModified = new Date().toISOString();
    this.metadata.secretCount = Object.keys(this.secrets).length;
    fs.writeFileSync(VAULT_META, JSON.stringify(this.metadata, null, 2));
  }
  
  set(key, value, provider) {
    this.secrets[key] = {
      value,
      provider,
      createdAt: this.secrets[key]?.createdAt || new Date().toISOString(),
      rotatedAt: new Date().toISOString(),
      version: (this.secrets[key]?.version || 0) + 1
    };
    this._save();
    console.log(`  ✅ ${key} guardado (v${this.secrets[key].version})`);
  }
  
  get(key) {
    return this.secrets[key]?.value;
  }
  
  list() {
    return Object.entries(this.secrets).map(([key, data]) => ({
      key,
      provider: data.provider,
      version: data.version,
      rotatedAt: data.rotatedAt,
      masked: data.value.slice(0, 4) + '****' + data.value.slice(-4)
    }));
  }
  
  delete(key) {
    delete this.secrets[key];
    this._save();
  }
  
  exportEnv() {
    let env = '# Generated by secret-rotator.js\n';
    env += `# Date: ${new Date().toISOString()}\n\n`;
    
    for (const [key, data] of Object.entries(this.secrets)) {
      const envKey = key.toUpperCase().replace(/[^A-Z0-9_]/g, '_');
      env += `${envKey}=${data.value}\n`;
    }
    
    return env;
  }
}

