// ─── CLI ────────────────────────────────────────────────────────────────────
function main() {
  const args = process.argv.slice(2);
  const passphrase = process.env.VAULT_PASSPHRASE;
  
  if (!passphrase) {
    console.error('❌ VAULT_PASSPHRASE no configurada');
    console.error('   Exporta: export VAULT_PASSPHRASE="tu-passphrase-segura"');
    process.exit(1);
  }
  
  if (args.includes('--help') || args.length === 0) {
    console.log(`
Secret Rotator — Pedro Belentani
Vault cifrado AES-256-GCM

Uso:
  node secret-rotator.js list                    Listar secretos
  node secret-rotator.js set <key> <value>       Guardar secreto
  node secret-rotator.js get <key>               Obtener secreto
  node secret-rotator.js delete <key>            Eliminar secreto
  node secret-rotator.js rotate <provider>       Guía de rotación
  node secret-rotator.js verify                  Verificar vault
  node secret-rotator.js export --env            Exportar como .env
  node secret-rotator.js providers               Proveedores disponibles

Proveedores: alibaba, huggingface, openrouter, groq
`);
    return;
  }
  
  const vault = new SecretVault(passphrase);
  const command = args[0];
  
  switch (command) {
    case 'list':
      console.log('\n🔐 Secretos en vault:\n');
      const list = vault.list();
      if (list.length === 0) {
        console.log('   (vacío)');
      } else {
        list.forEach(s => {
          console.log(`   ${s.key.padEnd(25)} ${s.provider.padEnd(15)} v${s.version}  ${s.masked}`);
        });
      }
      break;
      
    case 'set':
      if (args.length < 3) {
        console.error('Uso: set <key> <value>');
        return;
      }
      vault.set(args[1], args[2], args[1].split('_')[0]);
      break;
      
    case 'get':
      const val = vault.get(args[1]);
      if (val) console.log(val);
      else console.log('No encontrado');
      break;
      
    case 'delete':
      vault.delete(args[1]);
      console.log(`🗑️  ${args[1]} eliminado`);
      break;
      
    case 'rotate':
      const provider = args[1];
      if (provider === '--all') {
        console.log('\n🔄 Rotación de todos los proveedores:\n');
        Object.entries(rotators).forEach(([key, p]) => {
          console.log(`\n  ${p.name}:`);
          p.instructions.forEach(i => console.log(`    ${i}`));
        });
      } else if (rotators[provider]) {
        console.log(`\n🔄 Rotación: ${rotators[provider].name}\n`);
        rotators[provider].instructions.forEach(i => console.log(`  ${i}`));
      } else {
        console.log('Proveedor no encontrado. Usa: providers');
      }
      break;
      
    case 'providers':
      console.log('\n🏢 Proveedores configurables:\n');
      Object.entries(rotators).forEach(([key, p]) => {
        console.log(`  ${key.padEnd(15)} ${p.name} (env: ${p.envVar})`);
      });
      break;
      
    case 'verify':
      try {
        const testEncrypt = encrypt('test', passphrase);
        const testDecrypt = decrypt(testEncrypt, passphrase);
        if (testDecrypt === 'test') {
          console.log('✅ Vault operativo — cifrado/descifrado verificado');
          console.log(`   Secretos: ${vault.list().length}`);
          console.log(`   Última modificación: ${vault.metadata.lastModified || 'nunca'}`);
        }
      } catch (err) {
        console.error('❌ Error de verificación:', err.message);
      }
      break;
      
    case 'export':
      if (args.includes('--env')) {
        const envContent = vault.exportEnv();
        const envFile = path.join(VAULT_DIR, '.env.generated');
        fs.writeFileSync(envFile, envContent);
        console.log(`📄 .env generado: ${envFile}`);
        console.log('⚠️  Asegúrate de NO commitear este archivo');
      }
      break;
      
    default:
      console.log('Comando no reconocido. Usa --help');
  }
}

main();

module.exports = { SecretVault, encrypt, decrypt };
